import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const postcss = require('postcss');
const tailwind = require('@tailwindcss/postcss');
const preserveCascade = require('./component-cascade.cjs');
const directory = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const input = await fs.readFile(path.join(directory, 'app/globals.css'), 'utf8');
const result = await postcss([tailwind({ base: directory, optimize: false }), preserveCascade()]).process(input, { from: path.join(directory, 'app/globals.css') });
const output = postcss.root();
for (const node of result.root.nodes) {
  if (node.type === 'atrule' && node.name === 'layer' && node.params === 'theme') output.append(node.clone());
  if (node.type === 'rule') {
    const compiled = node.toString();
    if (/invoice-(?:export|pdf|admin)/.test(compiled) || compiled.includes('#tailwind-inline')) output.append(node.clone());
  }
}
const css = output.toString();
await fs.writeFile(path.join(directory, 'lib/invoice-tailwind-css.ts'), '/** Generated by npm run styles:invoice. Styling is compiled from Tailwind utilities. */\nexport const invoiceTailwindCss = ' + JSON.stringify(css) + ';\n');
console.log('Invoice Tailwind stylesheet generated.');
